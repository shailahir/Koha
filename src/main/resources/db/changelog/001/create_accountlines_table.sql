DROP TABLE IF EXISTS accountlines;

CREATE TABLE accountlines
(
    accountlines_id   integer     NOT NULL,
    issue_id          integer        DEFAULT NULL,
    old_issue_id      integer        DEFAULT NULL,
    borrowernumber    integer        DEFAULT NULL,
    itemnumber        integer        DEFAULT NULL,
    date              timestamp NULL DEFAULT NULL,
    amount            decimal(28, 6) DEFAULT NULL,
    description       text           DEFAULT NULL,
    credit_type_code  varchar(80)    DEFAULT NULL,
    debit_type_code   varchar(80)    DEFAULT NULL,
    credit_number     varchar(20)    DEFAULT NULL,
    status            varchar(16)    DEFAULT NULL,
    payment_type      varchar(80)    DEFAULT NULL,
    amountoutstanding decimal(28, 6) DEFAULT NULL,
    timestamp         timestamp   NOT NULL,
    note              text           DEFAULT NULL,
    manager_id        integer        DEFAULT NULL,
    register_id       integer        DEFAULT NULL,
    interface         varchar(16) NOT NULL,
    branchcode        varchar(10)    DEFAULT NULL,
    CONSTRAINT accountlines_pk PRIMARY KEY (accountlines_id),
    CONSTRAINT accountlines_ibfk_borrowers FOREIGN KEY (borrowernumber) REFERENCES borrowers (borrowernumber) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_borrowers_2 FOREIGN KEY (manager_id) REFERENCES borrowers (borrowernumber) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_branches FOREIGN KEY (branchcode) REFERENCES branches (branchcode) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_credit_type FOREIGN KEY (credit_type_code) REFERENCES account_credit_types (code) ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_debit_type FOREIGN KEY (debit_type_code) REFERENCES account_debit_types (code) ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_issues FOREIGN KEY (issue_id) REFERENCES issues (issue_id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_items FOREIGN KEY (itemnumber) REFERENCES items (itemnumber) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_old_issues FOREIGN KEY (old_issue_id) REFERENCES old_issues (issue_id) ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT accountlines_ibfk_registers FOREIGN KEY (register_id) REFERENCES cash_registers (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE INDEX accountlines_acctsborr_idx ON accountlines (borrowernumber);
CREATE INDEX accountlines_time_idx ON accountlines (timestamp);
CREATE INDEX accountlines_credit_type_code_idx ON accountlines (credit_type_code);
CREATE INDEX accountlines_debit_type_code_idx ON accountlines (debit_type_code);
CREATE INDEX accountlines_itemnumber_idx ON accountlines (itemnumber);
CREATE INDEX accountlines_branchcode_idx ON accountlines (branchcode);
CREATE INDEX accountlines_manager_id_idx ON accountlines (manager_id);
CREATE INDEX accountlines_accountlines_ibfk_registers_idx ON accountlines (register_id);
CREATE INDEX accountlines_accountlines_ibfk_old_issues_idx ON accountlines (old_issue_id);
CREATE INDEX accountlines_accountlines_ibfk_issues_idx ON accountlines (issue_id);

COMMENT
ON COLUMN accountlines.credit_number IS 'autogenerated number for credits';

COMMENT
ON COLUMN accountlines.payment_type IS 'optional authorised value PAYMENT_TYPE';

COMMENT
ON COLUMN accountlines.branchcode IS 'the branchcode of the library where a payment was made, a manual invoice created, etc.';
